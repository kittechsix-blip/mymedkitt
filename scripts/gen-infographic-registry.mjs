#!/usr/bin/env node
// Regenerate the infographic registry from the staged files in docs/infographics/.
//
// Produces two artifacts, both derived purely from which `<consult-id>.html` files exist:
//   1. src/data/infographic-registry.ts  — the Set the toolbar consults to gate the 📊 button.
//   2. docs/sw.js ASSETS_TO_CACHE        — the infographic files, inside sentinel markers,
//      so they precache for offline-first (a core myMedKitt requirement).
//
// Run after staging/removing any infographic. The /deploy skill's cache-sync then bumps
// CACHE_NAME so clients pick up the new precache list. Safe to run repeatedly (idempotent).
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const INFOGRAPHICS_DIR = join(ROOT, 'docs', 'infographics');
const REGISTRY_TS = join(ROOT, 'src', 'data', 'infographic-registry.ts');
const SW_JS = join(ROOT, 'docs', 'sw.js');

const BEGIN = '  // >>> INFOGRAPHICS (auto-generated by gen-infographic-registry.mjs) >>>';
const END = '  // <<< INFOGRAPHICS (auto-generated) <<<';

const ids = existsSync(INFOGRAPHICS_DIR)
  ? readdirSync(INFOGRAPHICS_DIR)
      .filter((f) => f.endsWith('.html'))
      .map((f) => f.replace(/\.html$/, ''))
      .sort()
  : [];

// 1. TS registry ------------------------------------------------------------
const registryTs = `// AUTO-GENERATED by scripts/gen-infographic-registry.mjs — DO NOT EDIT BY HAND.
// One entry per interactive infographic staged at docs/infographics/<consult-id>.html.
// Gates the 📊 Visual button in the contextual toolbar so it only appears where a
// validated infographic actually exists.

export const INFOGRAPHIC_CONSULTS: ReadonlySet<string> = new Set([
${ids.map((id) => `  '${id}',`).join('\n')}
]);

/** True when consult \`consultId\` has a staged interactive infographic. */
export function hasInfographic(consultId: string): boolean {
  return INFOGRAPHIC_CONSULTS.has(consultId);
}
`;
writeFileSync(REGISTRY_TS, registryTs);

// 2. SW precache block ------------------------------------------------------
let sw = readFileSync(SW_JS, 'utf8');
const block = [BEGIN, ...ids.map((id) => `  './infographics/${id}.html',`), END].join('\n');

if (sw.includes(BEGIN) && sw.includes(END)) {
  sw = sw.replace(new RegExp(`${escapeRe(BEGIN)}[\\s\\S]*?${escapeRe(END)}`), block);
} else {
  // First run: insert the managed block immediately after the array opener.
  sw = sw.replace(/const ASSETS_TO_CACHE = \[\n/, (m) => m + block + '\n');
}
writeFileSync(SW_JS, sw);

function escapeRe(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

console.log(`✓ infographic registry: ${ids.length} consult(s)`);
if (ids.length) console.log('  ' + ids.join(', '));
