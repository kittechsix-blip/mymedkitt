// Pure helpers for scripts/rapid-register.ts (also used by scripts/rapid-check.ts and the unit test).

/** Strip files are named <treeId>.ts and export one const named RAPID_ + treeId upper-cased, non-alphanumerics as "_". */
export function exportName(treeId: string): string {
  return 'RAPID_' + treeId.toUpperCase().replace(/[^A-Z0-9]/g, '_');
}

/** The full text of src/data/rapid/index.ts for the given tree ids (sorted by treeId here). */
export function renderIndex(treeIds: readonly string[]): string {
  const ids = [...treeIds].sort();
  const imports = ids.map((id) => `import { ${exportName(id)} } from './${id}.js';`).join('\n');
  const entries = ids.map((id) => `  [${exportName(id)}.treeId]: ${exportName(id)},`).join('\n');
  return `// myMedKitt — RAPID registry. A consult is "RAPID" iff it has an entry here.
// GENERATED by scripts/rapid-register.ts from the strip files in this folder: do not hand-edit.
// Strip files import types only, so they also load in Node (gate, proof page).
import type { RapidStrip } from './types.js';
${imports}

export const RAPID_STRIPS: Readonly<Record<string, RapidStrip>> = {
${entries}
};
`;
}

/** Strip file names (treeIds) from a directory listing: every .ts except the three infrastructure files. */
export function stripIdsFromFiles(files: readonly string[]): string[] {
  return files.filter((f) => f.endsWith('.ts') && !['types.ts', 'index.ts', 'approvals.ts'].includes(f)).map((f) => f.slice(0, -3)).sort();
}
